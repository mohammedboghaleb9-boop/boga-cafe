function singleOrigin(
  id: string,
  originId: string,
  fr: string,
  en: string,
  ar: string,
  prices: Product['prices'],
  sortOrder: number,
): Product {
  const origin = seedOrigins.find((o) => o.id === originId)!;
  return {
    id,
    slug: id.replace(/^so-/, 'single-origin-'),
    kind: 'single-origin',
    name: { ar, fr, en },
    tagline: {
      ar: `مصدر واحد: ${origin.region}`,
      fr: `Une seule origine : ${origin.region}`,
      en: `One origin: ${origin.region}`,
    },
    description: {
      ar: `قهوة ${origin.name.ar} 100% من منطقة ${origin.region}، تُحمَّص وحدها لإبراز طابعها.`,
      fr: `100 % ${origin.name.fr}, région ${origin.region}, torréfié seul pour révéler son caractère.`,
      en: `100% ${origin.name.en} from ${origin.region}, roasted on its own to show its character.`,
    },
    recipe: [{ originId, percent: 100 }],
    roastLevel: origin.roastLevel,
    tastingNotes: origin.tastingNotes,
    prices,
    featured: false,
    active: true,
    sortOrder,
  };
}
